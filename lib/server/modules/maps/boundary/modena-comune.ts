function isInsidePolygon(latitude: number, longitude: number, polygon: ReadonlyArray<Position>) {
  let inside = false;
  for (let index = 0; index < polygon.length - 1; index += 1) {
    const current = polygon[index];
    const next = polygon[index + 1];
    const intersects =
      current[1] > latitude !== next[1] > latitude &&
      longitude <
        ((next[0] - current[0]) * (latitude - current[1])) / (next[1] - current[1]) + current[0];
    if (intersects) inside = !inside;
  }
  return inside;
}

export function isWithinComuneOfModena(latitude: number, longitude: number): boolean {
  return modenaComunePolygons.some((polygon) => isInsidePolygon(latitude, longitude, polygon));
}
